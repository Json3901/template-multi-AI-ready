<#
.SYNOPSIS
  Copies the canonical skills and subagents to the folder each AI tool reads.
.DESCRIPTION
  Sources (edit these):
    .agents/skills/<name>/SKILL.md   skills / slash commands (read natively by Codex and Copilot)
    .claude/agents/<name>.md         subagents
  Generated (never edit by hand; they carry a GENERATED marker):
    .claude/skills/<name>/SKILL.md   Claude Code
    .cursor/commands/<name>.md       Cursor
    .agents/workflows/<name>.md      Antigravity
    .github/agents/<name>.agent.md   GitHub Copilot custom agents
  Generated files whose source was deleted are removed.
.EXAMPLE
  powershell -ExecutionPolicy Bypass -File .\scripts\sync-agents.ps1
#>
$ErrorActionPreference = 'Stop'
$root   = Split-Path -Parent $PSScriptRoot
$utf8   = New-Object System.Text.UTF8Encoding($false)
$marker = 'GENERATED by scripts/sync-agents.ps1'

function Read-Text($path) { [IO.File]::ReadAllText($path, $utf8) }

function Write-Text($path, $text) {
    $dir = Split-Path -Parent $path
    if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
    [IO.File]::WriteAllText($path, ($text -replace "`r`n", "`n"), $utf8)
}

function Split-Doc($path) {
    $text = Read-Text $path
    $m = [regex]::Match($text, '(?s)^---\r?\n(.*?)\r?\n---\r?\n(.*)$')
    if (-not $m.Success) { throw "No frontmatter in $path" }
    $front = $m.Groups[1].Value
    $get = {
        param($key)
        $f = [regex]::Match($front, "(?m)^$key\s*:\s*(.+?)\s*$")
        if ($f.Success) { $f.Groups[1].Value } else { $null }
    }
    $doc = @{ Name = (& $get 'name'); Description = (& $get 'description'); Body = $m.Groups[2].Value.TrimStart() }
    if (-not $doc.Name -or -not $doc.Description) { throw "Missing name or description in $path" }
    $doc
}

function Has-Marker($path) { (Test-Path $path) -and ((Read-Text $path).Contains($marker)) }

# 1. Remove what was generated before (hand-written files are left alone)
$claudeSkills = Join-Path $root '.claude\skills'
if (Test-Path $claudeSkills) {
    Get-ChildItem $claudeSkills -Directory | Where-Object { Has-Marker (Join-Path $_.FullName 'SKILL.md') } |
        ForEach-Object { Remove-Item $_.FullName -Recurse -Force }
}
foreach ($rel in @('.cursor\commands', '.agents\workflows', '.github\agents')) {
    $dir = Join-Path $root $rel
    if (Test-Path $dir) {
        Get-ChildItem $dir -File -Filter *.md | Where-Object { Has-Marker $_.FullName } | Remove-Item -Force
    }
}

# 2. Skills -> Claude, Cursor, Antigravity
$skills = @(Get-ChildItem (Join-Path $root '.agents\skills') -Directory |
    Where-Object { Test-Path (Join-Path $_.FullName 'SKILL.md') })
foreach ($s in $skills) {
    $d    = Split-Doc (Join-Path $s.FullName 'SKILL.md')
    $note = "<!-- $marker from .agents/skills/$($s.Name)/SKILL.md. Edit that file, then run the script. -->"

    # Generated folders were removed in step 1, so anything left with this name is hand-written
    if (Test-Path (Join-Path $claudeSkills $d.Name)) {
        throw "Hand-written .claude/skills/$($d.Name) already exists; rename one of them."
    }
    # Claude Code: copy the whole folder (supporting files too); user-invoked only
    Copy-Item $s.FullName (Join-Path $claudeSkills $d.Name) -Recurse -Force
    Write-Text (Join-Path $claudeSkills "$($d.Name)\SKILL.md") (
        "---`nname: $($d.Name)`ndescription: $($d.Description)`ndisable-model-invocation: true`n---`n$note`n`n$($d.Body)")

    # Cursor: plain Markdown command
    Write-Text (Join-Path $root ".cursor\commands\$($d.Name).md") "$note`n`n# $($d.Description)`n`n$($d.Body)"

    # Antigravity: workflow
    Write-Text (Join-Path $root ".agents\workflows\$($d.Name).md") (
        "---`ndescription: $($d.Description)`n---`n$note`n`n$($d.Body)")
}

# 3. Subagents -> GitHub Copilot custom agents
$agents = @()
$agentDir = Join-Path $root '.claude\agents'
if (Test-Path $agentDir) { $agents = @(Get-ChildItem $agentDir -File -Filter *.md) }
foreach ($a in $agents) {
    $d    = Split-Doc $a.FullName
    $note = "<!-- $marker from .claude/agents/$($a.Name). Edit that file, then run the script. -->"
    Write-Text (Join-Path $root ".github\agents\$($d.Name).agent.md") (
        "---`nname: $($d.Name)`ndescription: $($d.Description)`ntools: ['read', 'search', 'execute']`n---`n$note`n`n$($d.Body)")
}

Write-Host "Synced $($skills.Count) skills (Claude, Cursor, Antigravity) and $($agents.Count) subagents (Copilot)."
